#!/usr/bin/env node
/**
 * The chat box's strings, for translation (§19.3 item 3). widget.js has no i18n runtime: its text is English in the
 * code, wrapped in t( '…' ), and the plugin prints the translations as SigmaWidget.i18n. This script reads every
 * t( '…' ) call (with the translators comment before it) in apps/widget/src and writes
 * includes/class-widget-strings.php, where each string goes through __() so `wp i18n make-pot` finds it.
 *
 *   node scripts/widget-strings.mjs          write the PHP file (npm run build does this)
 *   node scripts/widget-strings.mjs --check  exit 1 when the PHP file is out of date
 */
import { readFileSync, readdirSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { join, relative } from 'node:path';
import { ROOT } from '../tests/bin/root.mjs';

const SRC = join( ROOT, 'apps/widget/src' );
const OUT = join( ROOT, 'includes/class-widget-strings.php' );

const files = ( dir ) => readdirSync( dir ).flatMap( ( f ) => ( statSync( join( dir, f ) ).isDirectory() ? files( join( dir, f ) ) : /\.(ts|tsx)$/.test( f ) ? [ join( dir, f ) ] : [] ) );
const CALL = /(?:\/\*\s*(translators:[^*]*?)\s*\*\/\s*)?(?<![\w.$])t\(\s*'((?:[^'\\\n]|\\.)*)'/g;
const unquote = ( s ) => JSON.parse( '"' + s.replace( /\\'/g, "'" ).replace( /"/g, '\\"' ) + '"' );
const php = ( s ) => "'" + s.replace( /\\/g, '\\\\' ).replace( /'/g, "\\'" ) + "'";

const strings = new Map();
for ( const file of files( SRC ).sort() ) {
	if ( relative( SRC, file ) === 'i18n.ts' ) continue;
	for ( const m of readFileSync( file, 'utf8' ).matchAll( CALL ) ) {
		const text = unquote( m[ 2 ] );
		const note = m[ 1 ] ? m[ 1 ].replace( /\s+/g, ' ' ) : strings.get( text ) || '';
		if ( /%(\d\$)?s/.test( text ) && ! note ) {
			console.error( `widget-strings: "${ text }" (${ relative( ROOT, file ) }) has a placeholder but no /* translators: */ comment.` );
			process.exit( 1 );
		}
		strings.set( text, note );
	}
}

const entries = [ ...strings ].sort( ( a, b ) => a[ 0 ].localeCompare( b[ 0 ] ) );
const body = entries
	.map( ( [ text, note ] ) => `\t\t\t${ php( text ) } => ${ note ? `/* ${ note } */ ` : '' }__( ${ php( text ) }, 'sigma' ),` )
	.join( '\n' );
const out = `<?php
/**
 * The chat box's own strings, translated for SigmaWidget.i18n (§19.3 item 3).
 *
 * Generated by scripts/widget-strings.mjs from the t( '…' ) calls in apps/widget/src: do not edit. Run
 * \`npm run build\` after changing a widget string.
 *
 * @package TwentyOnePress\\Sigma
 */

declare( strict_types=1 );

namespace TwentyOnePress\\Sigma;

defined( 'ABSPATH' ) || exit;

/**
 * The widget's English strings and their translations in the site's language.
 */
final class Widget_Strings {

	/**
	 * Only the strings whose translation differs from English (none on an English site), so the inline data
	 * stays small. The widget falls back to its own English for the rest.
	 *
	 * @return array<string, string>
	 */
	public static function translated(): array {
		$out = array();
		foreach ( self::all() as $english => $translated ) {
			if ( $translated !== $english ) {
				$out[ $english ] = $translated;
			}
		}
		return $out;
	}

	/**
	 * Every string, English => translation.
	 *
	 * @return array<string, string>
	 */
	public static function all(): array {
		// phpcs:disable WordPress.Arrays.MultipleStatementAlignment -- Generated.
		return array(
${ body }
		);
		// phpcs:enable
	}
}
`;

if ( process.argv.includes( '--check' ) ) {
	const now = existsSync( OUT ) ? readFileSync( OUT, 'utf8' ) : '';
	if ( now !== out ) {
		console.error( 'widget-strings: includes/class-widget-strings.php is out of date; run npm run build.' );
		process.exit( 1 );
	}
	console.log( `widget-strings: ${ entries.length } strings, up to date.` );
} else {
	writeFileSync( OUT, out );
	console.log( `widget-strings: ${ entries.length } strings → includes/class-widget-strings.php` );
}
